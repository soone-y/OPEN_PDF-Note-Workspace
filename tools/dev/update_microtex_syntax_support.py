"""Regenerate the portable note diagnostic vocabulary from pinned MicroTeX inputs."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
INPUTS = (
    "third_party/microtex/lib/macro/macro_def.cpp",
    "third_party/microtex/lib/core/formula_def.cpp",
    "third_party/microtex/lib/unimath/uni_symbol.cpp",
)
OUTPUT = ROOT / "src/math/math_syntax_support.h"
# Global definitions, privileged operations and unimplemented graphics are not
# part of the embedded application's supported formula language.
DISABLED = {"newcommand", "renewcommand", "newenvironment", "renewenvironment",
            "DeclareMathOperator", "addfont", "includegraphics"}


def generate() -> str:
    macro, formula, symbols = ((ROOT / path).read_text(encoding="utf-8") for path in INPUTS)
    commands = set(re.findall(r'\bmac\([^\n]*?"([A-Za-z]+)"\)', macro))
    commands.update(re.findall(r'\bcmd\(\d+,\s*"([A-Za-z]+)"', macro))
    commands.update(re.findall(r'\bdefMac\("([A-Za-z]+)"', macro))
    commands.update(re.findall(r'^\s*\{"([A-Za-z]+)",', formula, re.MULTILINE))
    commands.update(re.findall(r'^\s*\{0x[0-9a-fA-F]+,\s*[^,\n]+,\s*"([A-Za-z]+)"', symbols, re.MULTILINE))
    # Delimiter/environment tokens consumed by the parser instead of MacroInfo.
    commands.update({"begin", "end", "right"})
    environments = set(re.findall(r'\benv\(\d+,\s*"([A-Za-z*]+)"', macro))
    commands -= DISABLED
    if len(commands) < 2000 or len(environments) < 20:
        raise ValueError("MicroTeX declaration format changed; review the vocabulary extractor")
    lines = ["#pragma once", "// Generated by tools/dev/update_microtex_syntax_support.py.",
             "// Capability hints for note diagnostics; the backend validates full expressions."]
    for path in INPUTS:
        lines.append(f"// {path}: {hashlib.sha256((ROOT / path).read_bytes()).hexdigest()}")
    lines += ["#include <algorithm>", "#include <array>", "#include <string_view>",
              "", "namespace mathrender::syntax_support {"]
    for name, values in (("Commands", commands), ("Environments", environments)):
        lines.append(f"inline constexpr std::array<std::wstring_view, {len(values)}> k{name}{{{{")
        lines.extend(f'    L"{value}",' for value in sorted(values))
        lines += ["}};", f"[[nodiscard]] inline bool IsSupported{name[:-1]}(std::wstring_view name) noexcept {{",
                  f"    return std::binary_search(k{name}.begin(), k{name}.end(), name);", "}", ""]
    return "\n".join(lines + ["} // namespace mathrender::syntax_support", ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "MicroTeX diagnostic vocabulary is stale; regenerate it.\n")
        print("MicroTeX diagnostic vocabulary matches pinned sources.")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print("Updated src/math/math_syntax_support.h")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
